package com.ssafy.a605.backend.domain.replay.dto;

/**
 * 이동 지점의 갈래. 화면이 종류별로 걸러 보기 위한 것이고, <b>식별자 문자열을 파싱하지
 * 않게 하려고</b> 서버가 함께 내려준다 — {@code key} 의 생김새는 서버의 사정이다.
 */
public enum ReplayMarkKind {

    /** 일차 경계 7개. 브리핑 · 개장 · 수수료 무료 시작·종료 · 랭킹 암전 · 폐장 · 정산 발표 */
    BOUNDARY,

    /** 각 게임 월의 첫 Tick. 시즌당 80개라 목록의 대부분을 차지한다 */
    MONTH,

    /** 공모의 공시 · 청약 마감 · 상장 */
    IPO,

    /**
     * 공모 편성이 없는 상장. 코인 · 직상장 · SPAC · 이전상장이며 시즌 2 에 15 종 있다.
     *
     * <p>{@link #IPO} 와 나눈 것은 갈래 필터 때문이다 — 공모는 공시·마감·상장 셋이 한 벌로
     * 움직이지만 이쪽은 상장 한 점뿐이라, 같은 갈래에 넣으면 "공모" 칩이 공모 아닌 것을
     * 켜고 끈다.
     */
    LISTING,

    /** 각 일차의 마지막 가격 Tick */
    DAY_LAST_TICK
}
