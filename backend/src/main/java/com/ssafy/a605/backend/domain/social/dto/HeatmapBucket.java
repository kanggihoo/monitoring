package com.ssafy.a605.backend.domain.social.dto;

/**
 * 히트맵의 집계 단위 ({@code soc.md} §GET /api/v1/social/heatmap, 기획서 12.4.2).
 *
 * <p>종목 카테고리 셋에 현금을 더한 넷이다. {@code InstrumentCategory} 를 그대로 쓰지 않는 이유는
 * {@link #CASH} 가 종목이 아니기 때문이다 — 화면이 요구하는 분류가 종목 분류보다 하나 넓다.
 *
 * <p><b>종목 단위로 쪼개지 않는다.</b> 기획서 12.4.2 가 요구하는 것은 카테고리 단위이고, 종목별로
 * 내려주면 "지금 다들 엔비디아를 던지고 있다"가 보인다 — {@code rank.md} 11.6.2 가 막으려는 상위권
 * 미러링과 같은 성질의 정보다. 개인 식별이 불가능해도 집단행동을 유발한다.
 */
public enum HeatmapBucket {

    /** 나스닥 종목. */
    NASDAQ,

    /** 국내 종목. */
    KRX,

    /** 코인. */
    CRYPTO,

    /**
     * 원화·달러 현금의 합. 통화를 나누지 않는다 — 나누면 "환전했다"가 "팔았다"처럼 보인다.
     *
     * <p>이 버킷이 화면의 핵심이다. 기획서 12.4 비고가 현금 비중의 변화를 공포·탐욕의 지표로 못 박는다.
     */
    CASH
}
