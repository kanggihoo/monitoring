package com.ssafy.a605.backend.domain.ranking.dto;

/**
 * 리더보드의 트랙 ({@code rank.md} §리더보드는 같은 리소스의 여러 값이다). 응답 형태는 같고
 * 다른 것은 줄 세우는 기준뿐이므로 경로가 아니라 파라미터다.
 */
public enum RankingTrack {
    /** 시즌 누적 수익률. 계좌 요약의 {@code cumulativeReturn} 기준 */
    SEASON,
    /** 당일 수익률. 계좌 요약의 {@code dailyReturn} 기준 */
    DAILY,
    /**
     * 총평가액. 유일하게 비율이 아니라 <b>금액</b>으로 줄 세우는 트랙이다.
     *
     * <p><b>시즌 누적과 순서가 거의 같다</b> — 전원 시드가 같으면 누적 수익률과 평가액은 같은
     * 사실의 두 단위다. 둘이 갈리는 것은 시작 잔고가 다른 중간 합류자(소급 인덱스 잔고)뿐이고,
     * 그 경우 이 트랙은 "얼마를 굴리고 있는가"를, 시즌 트랙은 "자기 시드를 얼마나 불렸는가"를
     * 말한다.
     */
    VALUATION,
    /**
     * 일간 순위 포인트 합 ({@code S15P21A605-250}).
     *
     * <p><b>다른 셋과 출처가 다르다.</b> 셋은 매 틱 재계산되는 {@link RankingSnapshot} 에서
     * 오지만 이 트랙은 {@code daily_settlements} 에서 온다 — 점수는 <b>폐장에 확정된 일간
     * 순위</b>로만 매겨지므로 진행 중인 오늘은 아직 점수가 없다. 그래서 갱신도 틱마다가
     * 아니라 하루 한 번이고, {@code rankDelta} 는 항상 0 이다 (비교할 직전 틱이 없다).
     *
     * <p>줄 세우는 값은 점수 합이고 동점은 일간 1 등 횟수 → 일간 수익률 합계 순으로 가른다.
     */
    POINT
}
