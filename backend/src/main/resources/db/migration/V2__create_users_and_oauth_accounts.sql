-- 사람(User)과 그 사람의 외부 IdP 신원(OAuth Account)을 나눠 담는다.
--
-- 동일인 판정은 (provider, provider_user_id) 로만 한다. 이메일은 표시용 속성이라
-- 이메일로 계정을 자동 연결하면 pre-account takeover 경로가 된다.
CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 이메일·닉네임에 UNIQUE 를 걸지 않는다. 닉네임에 걸면 동명이인의 첫 로그인이
    -- 실패하는데, 이는 로그인 자체가 막히는 가장 나쁜 실패 형태다.
    email      VARCHAR(255) NOT NULL,
    nickname   VARCHAR(50)  NOT NULL,
    -- 한 사람이 동시에 여러 역할을 가질 이유가 아직 없어 단일 컬럼으로 둔다.
    role       VARCHAR(20)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL
);

-- 한 User 는 여러 OAuth Account 를 가질 수 있다 (1:N). 계정 연결 기능은 만들지
-- 않으므로 지금은 User 당 행이 하나만 생긴다.
CREATE TABLE oauth_accounts
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id),
    provider         VARCHAR(20)  NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    CONSTRAINT uk_oauth_accounts_provider_user UNIQUE (provider, provider_user_id)
);
