-- 닉네임에 유니크를 건다. V2 는 일부러 걸지 않았고 그 판단에는 근거가 있었다:
--
--   "닉네임에 걸면 동명이인의 첫 로그인이 실패하는데, 이는 로그인 자체가 막히는
--    가장 나쁜 실패 형태다."
--
-- 그 근거는 닉네임 초기값이 IdP 값이라는 전제에 서 있었다. 구글 닉네임이 같은 사람이
-- 둘이면 두 번째 사람의 가입이 제약에 걸려 죽고, 카카오는 닉네임 미동의 사용자 전원이
-- 같은 대체값을 받아 더 심했다.
--
-- 기획서 1.1.4 대로 가입 시 닉네임을 시스템이 만들면(투자자 + 4자리 난수) 그 전제가
-- 사라진다. 값을 우리가 정하므로 충돌하면 다시 뽑으면 되고 로그인은 죽지 않는다.
-- 그래서 이제 유니크를 걸 수 있고, 걸어야 한다 - 기획서 2.1.3 의 유일성 검사를
-- 애플리케이션 조회만으로 지키면 동시 요청 둘이 같은 값을 통과한다.
ALTER TABLE users
    ADD CONSTRAINT uk_users_nickname UNIQUE (nickname);

COMMENT ON COLUMN users.nickname IS '표시 이름. 가입 시 시스템이 만들고(투자자 + 4자리 난수) 사용자가 마이페이지에서 바꾼다. 유일하며 금칙어 사전(forbidden_words)을 통과한 값만 허용한다';
