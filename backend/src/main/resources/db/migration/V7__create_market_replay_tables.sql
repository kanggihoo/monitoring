-- 마켓 리플레이 — 게임 도메인 테이블 23개. (S15P21A605-32)
--
-- 근거는 docs/specs/market-replay/ 의 API 명세다. 테이블마다 어느 문서에서 왔는지
-- COMMENT 에 적었다. 순서는 FK 의존 순이라 그대로 실행된다.
--
-- 역정규화 3건 — 새로 생긴 nullable 컬럼은 없다.
--   fx_rates      -> game_ticks.usd_krw   환율은 거래일당 1개 값이라 틱과 grain 이 같다
--   daily_reports -> daily_settlements    PK 와 기록 시점(폐장 스냅샷)이 같고
--                                         daily_return·finalized_at 이 중복이었다
--   awards        -> 테이블 없음          일간 1위 = daily_rank 1, 시즌 우승 = 3일차
--                                         season_rank 1. daily_settlements 가 이미
--                                         확정 스냅샷이라 재계산이 아니라 조회다
--
-- 온보딩(기획서 14장)은 테이블을 만들지 않는다. 저장할 것이 "가이드를 끝까지 봤는가"
-- 하나뿐이라 accounts.onboarding_completed_at 컬럼으로 충분하다.
--
-- 이번 범위에서 제외: chat_reports(채팅 신고), user_restrictions(이용 제재).
-- 둘 다 잎 테이블이라 나중에 별도 마이그레이션으로 추가해도 여기 있는 것들은 안 깨진다.
--
-- 이 리포의 규약대로 FK 는 걸되 ON DELETE CASCADE 는 쓰지 않는다. 다만 탈퇴가
-- users 를 물리 삭제하므로, 탈퇴 후에도 남아야 하는 기록(chat_messages.user_id,
-- chat_messages.deleted_by)에는 FK 를 걸지 않는다. 참조가 아니라 "그 시점의 기록"이다.
--
-- 인덱스는 PK·UNIQUE 외에 잡지 않았다. 조회 패턴이 확정되면 별도 버전으로 추가한다.

CREATE TABLE seasons
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100)  NOT NULL,
    start_date         DATE          NOT NULL,
    end_date           DATE          NOT NULL,
    seed_krw           NUMERIC(20, 4) NOT NULL,
    trade_fee_rate     NUMERIC(9, 4)  NOT NULL,
    exchange_fee_rate  NUMERIC(9, 4)  NOT NULL,
    ipo_winner_ratio   NUMERIC(9, 4)  NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL
);

COMMENT ON TABLE seasons IS '시즌 1건. 지금은 3일짜리 하나뿐이지만, 편성값(시드·요율·추첨 비율)을 코드 상수로 두지 않기 위해 테이블로 만든다';
COMMENT ON COLUMN seasons.start_date IS '운영 시작일 (기획서 3.1.1)';
COMMENT ON COLUMN seasons.end_date IS '운영 종료일';
COMMENT ON COLUMN seasons.seed_krw IS '시드 머니. 기획서 v0.7 기준 1억 원';
COMMENT ON COLUMN seasons.trade_fee_rate IS '거래 수수료율(%). 0.15 = 0.15%. 무료 타임에는 0 이 적용된다';
COMMENT ON COLUMN seasons.exchange_fee_rate IS '환전 수수료율(%). 0.05. 무료 타임 대상이 아니다';
COMMENT ON COLUMN seasons.ipo_winner_ratio IS 'IPO 당첨 예정 인원 비율(%). 기본 30 (기획서 8.4.2)';
COMMENT ON COLUMN seasons.id IS '시즌 식별자';
COMMENT ON COLUMN seasons.name IS '시즌 표시 이름';
COMMENT ON COLUMN seasons.created_at IS '생성 시각';


