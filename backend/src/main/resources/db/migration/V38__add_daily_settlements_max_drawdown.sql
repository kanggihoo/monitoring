-- 폐장 시점의 누적 최대 낙폭 스냅샷 (AI 업무요청서 2026-09-18 요청 ②).
--
-- **소급이 불가능해서 여기 둔다.** accounts.max_drawdown 은 시즌 누적 한 값이고 매 틱 갱신된다
-- (Account.observeValuation). 평가액 시계열을 저장하는 곳이 없으므로 — V26 이 "시계열을 저장하는
-- 대신 최고점만 들고 다닌다"고 정한 그대로다 — 2일차가 시작되면 1일차 시점의 낙폭은 영구히
-- 복원할 수 없다. 일차 경계에서 그때의 값을 찍어 두는 것이 유일한 길이다.
--
-- 이 값으로 AI 일일 요청의 cumulative.maxDrawdown 을 채운다. 그것 없이 시즌 누적을 1·2일차에
-- 그대로 보내면 AI 의 고정 참조 사분위 표에서 가장 흔들리는 항목이 한쪽으로 쏠린다.
--
-- **시계열을 만드는 것이 아니다.** 일차당 한 점이고 시즌 전체가 세 점이다. 그 세 점은 낙폭을
-- 새로 계산하기 위한 것이 아니라 이미 계산된 값을 그 시점에 고정하기 위한 것이다.
ALTER TABLE daily_settlements
    ADD COLUMN max_drawdown numeric(9, 4);

-- 기존 행은 비운다. 채울 수 있는 값이 없다 — 지금의 accounts.max_drawdown 은 그 일차가 아니라
-- 현재까지의 누적이라, 넣으면 1·2일차에 3일차 값이 들어간 것처럼 보인다. NULL 은 "그 일차에
-- 찍지 못했다"는 뜻이고, 읽는 쪽은 그 계좌의 그 일차 낙폭을 보내지 않는다.
COMMENT ON COLUMN daily_settlements.max_drawdown IS
    '폐장 시점의 시즌 누적 최대 낙폭(%). 최고점 대비 하락률이라 음수이거나 0 이다. 이 칼럼이 생기기 전의 행은 NULL';
