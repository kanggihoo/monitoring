-- 금칙어 사전. 채팅 본문과 닉네임이 공용으로 쓴다 (기획서 12.2.2, soc.md).
--
-- 단어를 코드 상수로 두지 않는 이유는 두 가지다. 목록이 운영 중에 늘어나는 성질의 데이터이고,
-- 무엇이 금칙어인지가 코드 리뷰와 커밋 로그에 남으면 그 자체가 우회 안내가 된다.
--
-- 이번 범위는 테이블뿐이다. 단어 적재는 별도 작업이며, 사전이 비어 있으면 마스킹이 하나도
-- 걸리지 않는 상태로 정상 동작한다 - 필터는 빈 사전을 예외가 아니라 통과로 다룬다.
--
-- 차단이 아니라 마스킹이다. 전송은 성공하고 본문만 * 로 덮인다 - 어느 단어가 걸렸는지 알려주면
-- 우회 방법을 알려주는 셈이고, 사용자는 "왜 안 보내지나"를 모른 채 여러 번 시도한다.

CREATE TABLE forbidden_words
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word       VARCHAR(50) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL
);

COMMENT ON TABLE forbidden_words IS '금칙어 사전 (기획서 12.2.2). 채팅 본문과 닉네임이 공용으로 쓴다. 차단이 아니라 마스킹의 근거이며, 비어 있으면 아무것도 마스킹되지 않는다';
COMMENT ON COLUMN forbidden_words.word IS '금칙어 한 단어. 대소문자 구분 없이 매칭하므로 소문자로 저장한다. UNIQUE 가 중복 적재를 막는다';
COMMENT ON COLUMN forbidden_words.created_at IS '등록 시각';
