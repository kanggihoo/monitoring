-- 관리자 권한으로 수행된 행위의 불변 기록. 추가만 가능하다.
--
-- users 에 FK 를 걸지 않는다: 탈퇴가 hard delete 라, FK 를 걸면 대상이 된 사용자의 탈퇴가
-- 실패하거나(RESTRICT) 감사 기록이 함께 사라진다(CASCADE). 감사 로그는 대상이 사라져도
-- 남아야 한다. 그래서 여기의 사용자 식별자는 "그 시점에 그 값이었다"는 기록이지 참조가 아니다.
--
-- 접속 주소와 클라이언트 정보 컬럼은 만들지 않는다. 리버스 프록시 설정이 이 리포에 없어
-- 배포에서는 모든 행에 프록시 주소가 들어가 정보량이 0 이다.
CREATE TABLE admin_audit_logs
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id  BIGINT      NOT NULL,
    -- USER_ROLE_UPDATE | SESSION_REVOKE. 샌드박스 진입은 남기지 않는다 (ADR-0003 8번).
    action         VARCHAR(30) NOT NULL,
    target_user_id BIGINT,
    -- 예: 'USER -> ADMIN'. 저장 실패가 나지 않도록 넣기 전에 잘라 담는다.
    detail         VARCHAR(255),
    created_at     TIMESTAMPTZ NOT NULL
);
