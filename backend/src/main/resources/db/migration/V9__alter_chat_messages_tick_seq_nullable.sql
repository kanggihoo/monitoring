-- 채팅의 게임 시각을 선택값으로 바꾼다.
--
-- V7 은 tick_seq 를 NOT NULL 로 잡았는데, 채팅이 가능한 시간과 틱이 있는 시간이 다르다.
-- 기획서 12.1.2 는 운영 시간 11:00~17:00 내내 전송을 허용하지만, 재생은 11:05 에 시작해
-- 약 16:29 에 끝난다. 그래서 세 구간에서 참조할 틱이 없다.
--
--   11:00~11:05  브리핑        아직 그날 첫 틱이 나가지 않았다
--   16:29~17:00  재생 종료 후  그날 마지막 틱이 이미 지났다
--   1일차 브리핑              시즌 전체에 틱이 하나도 없다
--
-- 마지막 경우가 결정적이다. 직전 틱으로 채워 넣는 우회가 1일차 11:00 에는 성립하지
-- 않는다. 시즌 첫 채팅 한 줄이 FK 위반으로 실패한다.
--
-- 값을 지어내지 않고 NULL 을 허용한다. 조회 응답의 gameDate 도 함께 null 이 되고,
-- 화면은 게임 시각 표기를 생략한다. notifications.tick_seq 가 폐장 자동 취소를 위해
-- 이미 같은 판단을 하고 있다.
ALTER TABLE chat_messages
    ALTER COLUMN tick_seq DROP NOT NULL;

COMMENT ON COLUMN chat_messages.tick_seq IS '보낸 시점의 게임 시각. 나중에 "폭락 때 사람들이 뭐라고 했나"를 볼 수 있어야 한다. 재생 중이 아닌 시간(브리핑·재생 종료 후·정산 처리)에 보낸 메시지는 NULL 이며, 응답의 gameDate 도 함께 null 이다';
