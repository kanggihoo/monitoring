-- 금칙어 사전 보강 - 완성형 음절 사이에 글자를 끼우는 우회 (S15P21A605).
--
-- V22 는 변형을 손으로 나열했고 그 목록이 자모 형태에 치우쳐 있었다. ㅅ1발 · ㅆ1발 · ㅆ!발 ·
-- ㅆi발 · ㅆl발 · ^^l발 은 있는데 완성형인 씨1발 이 없어서 닉네임으로 통과했다. 씨ㅣ발 ·
-- 씨ㅡ발 처럼 완성형 + 자모 조합은 있으므로 빠진 것은 "완성형 + 숫자·영문·기호" 한 부류다.
--
-- 그래서 뿌리 단어 26개에 대해 음절 경계마다 9종(1 l i I ! * - _ 0)을 끼운 조합을 채운다.
-- 288 건이며 V22 와 겹치는 것이 하나도 없다 - 이 부류가 통째로 비어 있었다는 뜻이다.
--
-- 뿌리는 V22 에 기본형이 이미 있는 것만 골랐다. 등신 · 닥쳐 · 꺼져 는 V22 가 넣지 않았으므로
-- 여기서도 넣지 않는다 (닥쳐 는 아가리닥쳐 로만 등재돼 있다) - 사전에 없는 말의 변형을 막으면
-- 기본형은 통과하는데 변형은 걸리는 뒤집힌 상태가 된다.
--
-- 구분자에서 마침표를 뺐다. 한글은 단어 경계를 요구하지 않고 부분 문자열로 찾으므로
-- "다시.발표" 가 시.발 로, "김씨.발표" 가 씨.발 로 걸린다. 시 · 씨 · 발 이 전부 흔한 음절이라
-- 이 조합만 오탐이 실제로 난다.
--
-- 이것으로 우회가 끝나지 않는다. 나열로 막는 방식은 조합이 곱으로 늘어나 원리상 따라잡지
-- 못한다 - 매칭 전에 본문과 사전을 같은 규칙으로 접는 정규화가 제대로 된 해법이고, 그것은
-- 사전 재정리와 오탐 회귀 테스트를 함께 해야 하는 별도 작업이다.

