-- 문의 하나와 그에 대한 답변 하나. 스레드가 아니므로 재질문은 새 행이다.
--
-- 답변을 별도 테이블로 분리하지 않는다: 1:1 이고 스레드가 아니라 같은 행에 담는다.
-- 나중에 스레드가 필요해지면 그때 쪼개는 것이 지금 쓰지 않을 테이블을 만드는 것보다 싸다.
CREATE TABLE inquiries
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- FK 는 걸되 CASCADE 는 걸지 않는다. 탈퇴 시 서비스가 명시적으로 지운다
    -- (기존 oauth_accounts 처리와 같은 결). DB CASCADE 에 맡기면 JPA 1차 캐시와 어긋난다.
    user_id     BIGINT        NOT NULL REFERENCES users (id),
    title       VARCHAR(100)  NOT NULL,
    content     VARCHAR(2000) NOT NULL,
    -- OPEN | ANSWERED. 처리 중·보류 같은 중간 상태를 만들지 않는다.
    status      VARCHAR(20)   NOT NULL,
    answer      VARCHAR(2000),
    -- FK 를 걸지 않는다. 답변한 관리자가 탈퇴할 수 있고, 그때 답변이 사라지거나
    -- 탈퇴가 실패하면 안 된다. 이 값은 "그 시점에 그 사람이 답했다"는 기록이다.
    answered_by BIGINT,
    answered_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL
);
